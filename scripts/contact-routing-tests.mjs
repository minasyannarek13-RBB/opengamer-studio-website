import assert from "node:assert/strict";
import test from "node:test";
import { readFile } from "node:fs/promises";

const leadFormSource = await readFile(new URL("../components/forms/LeadForm.tsx", import.meta.url), "utf8");
const contactSource = await readFile(new URL("../app/contact/page.tsx", import.meta.url), "utf8");
const servicesSource = await readFile(new URL("../app/services/page.tsx", import.meta.url), "utf8");

test("contact routes dedicated capacity through its own enquiry context", () => {
  assert.match(contactSource, /interest=dedicated/);
  assert.match(leadFormSource, /dedicated:\s*"Dedicated Development Team"/);
});

test("live casino enquiry language maps to product design without certification or studio-operation claims", () => {
  assert.match(leadFormSource, /"live-casino":\s*"Live Casino Product Design"/);
  assert.match(leadFormSource, /"live casino development":\s*"Live Casino Product Design"/);
});

test("service page labels generated by CTA links are normalized by the lead form", () => {
  const expectedAliases = [
    "game production",
    "custom slot development",
    "turnkey slot development",
    "technology & integration",
    "backend & rgs engineering",
    "game integration",
    "platform integration",
    "portfolio & product",
    "white-label games",
    "live casino product",
    "dedicated delivery",
    "dedicated teams",
    "certification preparation support"
  ];

  for (const alias of expectedAliases) {
    assert.match(leadFormSource.toLowerCase(), new RegExp(`(?:\\"|')?${alias.replace(/[.*+?^${}()|[\\]\\]/g, "\\$&")}(?:\\"|')?\\s*:`));
  }

  assert.match(servicesSource, /contact\?service=/);
});
